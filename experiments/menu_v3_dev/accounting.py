"""Exhaustive, mutually exclusive accounting of every menu-v3 candidate outcome (720 = 60 incidents x 12 items).

Each row falls in exactly one class:
  infrastructure_error   the re-execution itself failed (no verdict)
  non_completion         the job never committed its final checkpoint (hang, crash, timeout)
  valid_reference        completed, semantically valid, and the item restores the conventional code at the fault's
                         location (B_OK: the no-change relaunch)
  valid_alternative      completed, semantically valid, any other item (rewrites, and no-op edits on a healthy job)
  incorrect_completed    completed but semantically invalid (the job finishes with corrupted training or a changed world)
"Semantically valid" is the oracle label: the final model equals the uninterrupted reference run's within tolerance,
every sample was consumed as in the reference, ranks agree and the world size is unchanged. It is computed from the run's
launcher records by a different predicate than the verifier's checks, not from the item's role or author intent.
Verdict agreement between two executions (local vs sandboxed) is a separate, weaker statement: it shows reproducibility,
not correctness. Writes ACCOUNTING.md next to this file (overwrites only its own generated file).

  python experiments/menu_v3_dev/accounting.py"""
from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
R = HERE / "results"
CHECKS = ("v1", "v1.1", "v1.2")
LOCATION = {("A1", 0): "sync:canonical", ("A1", 1): "perrank:canonical", ("A2", 0): "shard:canonical",
            ("B_SKIP", 0): "ckpt:canonical", ("B_DUP", 0): "ckpt:canonical", ("B_OK", 0): "relaunch"}


def rows(*runs):
    return [json.loads(x) for run in runs for x in (R / run / "outcomes.jsonl").read_text().splitlines()]


def semantic_valid(o: dict) -> bool:
    return bool(o["ckpt_valid"] and o["params_match_reference"] and o["samples_match_reference"]
                and o["ranks_consistent"] and "I6" not in o["detail"])


def klass(r: dict) -> str:
    if r["status"] != "ran":
        return "infrastructure_error"
    o = r["checks"]["v1.2"]          # completion and the oracle do not depend on the check version (same run)
    if not o["ckpt_valid"]:
        return "non_completion"
    if not semantic_valid(o):
        return "incorrect_completed"
    return "valid_reference" if r["role"] == LOCATION[(r["kind"], r["variant"])] else "valid_alternative"


def main() -> int:
    ver = rows("dev1_modal_s1b", "dev1_modal_s2")
    loc = {(r["seed"], r["cand_id"]): r for r in rows("dev1")}
    assert len(ver) == 720 and len({(r["seed"], r["cand_id"]) for r in ver}) == 720 and set(loc) == {(r["seed"], r["cand_id"]) for r in ver}
    cls = Counter(klass(r) for r in ver)
    assert sum(cls.values()) == 720
    L = ["# Menu v3 candidate accounting (generated by accounting.py)", "",
         "720 candidate re-executions (60 incidents x 12 items), Modal gVisor sandboxed (`dev1_modal_s1b`, `dev1_modal_s2`).",
         "Classes are exhaustive and mutually exclusive; the oracle is the independent semantic reference (see script docstring).", "",
         "| class | rows |", "|---|---|"] + [f"| {k} | {cls[k]} |" for k in
         ("valid_reference", "valid_alternative", "incorrect_completed", "non_completion", "infrastructure_error")] + \
        [f"| **total** | **{sum(cls.values())}** |", "",
         "Verifier verdicts against the oracle (denominators: valid = valid_reference + valid_alternative; incorrect = incorrect_completed;",
         "non-completions and infrastructure errors are not semantic judgements and are reported apart):", "",
         "| check | accepted valid | false rejections (valid not accepted) | accepted incorrect (false acceptances) | accepted non-completions |",
         "|---|---|---|---|---|"]
    valid = [r for r in ver if klass(r) in ("valid_reference", "valid_alternative")]
    bad = [r for r in ver if klass(r) == "incorrect_completed"]
    nonc = [r for r in ver if klass(r) == "non_completion"]
    for fc in CHECKS:
        acc = lambda rs: sum(r["checks"][fc]["ok"] for r in rs)  # noqa: E731
        L.append(f"| {fc} | {acc(valid)}/{len(valid)} | {len(valid) - acc(valid)}/{len(valid)} | {acc(bad)}/{len(bad)} | {acc(nonc)}/{len(nonc)} |")
    fr = Counter((r["kind"], r["role"]) for r in valid if not r["checks"]["v1"]["ok"])
    L += ["", f"v1 false rejections by (kind, item): {dict(fr)}.", "",
          "Breakdown of the valid and incorrect classes by item (rows):", "", "| item | valid_reference | valid_alternative | incorrect_completed | non_completion |", "|---|---|---|---|---|"]
    by = Counter((r["role"], klass(r)) for r in ver)
    for role in sorted({r["role"] for r in ver}):
        L.append(f"| `{role}` | {by[(role, 'valid_reference')]} | {by[(role, 'valid_alternative')]} | {by[(role, 'incorrect_completed')]} | {by[(role, 'non_completion')]} |")
    agree_ok = {fc: sum(loc[(r['seed'], r['cand_id'])]["checks"][fc]["ok"] == r["checks"][fc]["ok"] for r in ver) for fc in CHECKS}
    agree_cls = sum(klass(loc[(r["seed"], r["cand_id"])]) == klass(r) for r in ver)
    bit = {fc: sum(loc[(r['seed'], r['cand_id'])]["checks"][fc]["bit_identical"] != r["checks"][fc]["bit_identical"] for r in ver) for fc in CHECKS}
    L += ["", "Reproducibility (local unsandboxed `dev1` vs sandboxed rows; agreement, not correctness):", "",
          f"- verdict (`ok`) agreement: " + ", ".join(f"{fc} {agree_ok[fc]}/720" for fc in CHECKS) + ";",
          f"- oracle class agreement: {agree_cls}/720;",
          f"- `bit_identical` differs on " + ", ".join(f"{fc} {bit[fc]}/720" for fc in CHECKS) +
          " rows (bit-level equality with the reference differs between the Linux sandbox and the macOS run; numerics stay within the verifier's tolerance, so verdicts are unaffected).",
          "", "Limit: the oracle and the verifier read the same launcher records, so a defect in what the launcher records would affect both;",
          "the oracle is independent of the verifier's checks and of item roles, not of the execution itself."]
    (HERE / "ACCOUNTING.md").write_text("\n".join(L) + "\n")
    print("\n".join(L[:14]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
